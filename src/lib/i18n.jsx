export const fmt = (str, vars = {}) => String(str).replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : vars[k]));

const MOOD_KEYS = { 'Tâm sự': 'mTamsu', 'Buồn': 'mBuon', 'Nhớ': 'mNho', 'Áp lực': 'mApluc', 'Vui': 'mVui', 'Tình yêu': 'mTinhyeu', 'Khác': 'mKhac', 'Thư tương lai': 'future' };

function readLang() {
  try { const v = localStorage.getItem('jomi-lang'); if (v === 'en' || v === 'vi') return v; } catch (e) { /* bỏ qua */ }
  return 'vi';
}

const LangContext = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLang] = useState(readLang);
  useEffect(() => {
    try { localStorage.setItem('jomi-lang', lang); } catch (e) { /* bỏ qua */ }
    document.documentElement.lang = lang;
  }, [lang]);
  const t = DICT[lang];
  const value = {
    lang, setLang, t,
    f: (key, vars) => fmt(vars && vars.n === 1 && t[`${key}_one`] ? t[`${key}_one`] : t[key], vars),
    moodName: (m) => (MOOD_KEYS[m] ? t[MOOD_KEYS[m]] : m),
    moodLabel: (l) => (l.mood === 'Khác' && l.mood_custom ? `${t.mKhac} · ${l.mood_custom}` : (MOOD_KEYS[l.mood] ? t[MOOD_KEYS[l.mood]] : l.mood)),
    timeAgo: (d) => {
      const s = (Date.now() - new Date(d).getTime()) / 1000;
      if (s < 60) return t.justNow;
      if (s < 3600) return fmt(t.minAgo, { n: Math.floor(s / 60) });
      if (s < 86400) return fmt(t.hoursAgo, { n: Math.floor(s / 3600) });
      if (s < 86400 * 2) return t.yesterday;
      if (s < 86400 * 7) return fmt(t.daysAgo, { n: Math.floor(s / 86400) });
      const x = new Date(d);
      return `${String(x.getDate()).padStart(2, '0')}/${String(x.getMonth() + 1).padStart(2, '0')}/${x.getFullYear()}`;
    },
  };
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);

export function LangSwitch({ className = '' }) {
  const { lang, setLang, t } = useLang();
  return (
    <div className={`lang-sw ${className}`} role="group" aria-label={t.langLabel}>
      <button className={lang === 'vi' ? 'lang-btn is-on' : 'lang-btn'} aria-pressed={lang === 'vi'} lang="vi" title="Tiếng Việt" onClick={() => setLang('vi')}>VI</button>
      <button className={lang === 'en' ? 'lang-btn is-on' : 'lang-btn'} aria-pressed={lang === 'en'} lang="en" title="English" onClick={() => setLang('en')}>EN</button>
    </div>
  );
}
